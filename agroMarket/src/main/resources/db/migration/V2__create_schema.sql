-- V2: create application schema for production
-- usuarios (single table for all user types)
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL,
  correo VARCHAR(255) NOT NULL UNIQUE,
  contrasena VARCHAR(255) NOT NULL,
  telefono VARCHAR(100) NOT NULL,
  rol VARCHAR(50) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- productos
CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL,
  descripcion TEXT,
  precio DECIMAL(19,2) NOT NULL,
  cantidad_disponible INT NOT NULL,
  imagen_url VARCHAR(1024),
  tipo_fruta VARCHAR(100) NOT NULL,
  productor_id BIGINT NOT NULL,
  en_promocion BOOLEAN NOT NULL DEFAULT FALSE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_productor FOREIGN KEY (productor_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

-- pedidos
CREATE TABLE IF NOT EXISTS pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comprador_id BIGINT NOT NULL,
  producto_id BIGINT NOT NULL,
  cantidad INT NOT NULL,
  precio_unitario DECIMAL(19,2) NOT NULL,
  total DECIMAL(19,2) NOT NULL,
  estado VARCHAR(50) NOT NULL,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pedido_comprador FOREIGN KEY (comprador_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
  CONSTRAINT fk_pedido_producto FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE RESTRICT
);

-- pagos
CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL UNIQUE,
  monto DECIMAL(19,2) NOT NULL,
  metodo_pago VARCHAR(50) NOT NULL,
  estado VARCHAR(50) NOT NULL,
  referencia_pasarela VARCHAR(255),
  fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pago_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id) ON DELETE CASCADE
);

-- facturas
CREATE TABLE IF NOT EXISTS facturas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL UNIQUE,
  subtotal DECIMAL(19,2) NOT NULL,
  impuesto DECIMAL(19,2) NOT NULL,
  total DECIMAL(19,2) NOT NULL,
  fecha_emision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  numero_factura VARCHAR(255) NOT NULL UNIQUE,
  CONSTRAINT fk_factura_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id) ON DELETE CASCADE
);

-- envios
CREATE TABLE IF NOT EXISTS envios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL UNIQUE,
  direccion_destino VARCHAR(1024) NOT NULL,
  estado VARCHAR(50) NOT NULL,
  transportista VARCHAR(255),
  guia VARCHAR(255),
  fecha_estimada_entrega DATE,
  origen VARCHAR(255) NOT NULL DEFAULT 'Chigorodo, Antioquia',
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_envio_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id) ON DELETE CASCADE
);

-- resenas
CREATE TABLE IF NOT EXISTS resenas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comprador_id BIGINT NOT NULL,
  producto_id BIGINT NOT NULL,
  calificacion INT NOT NULL,
  comentario VARCHAR(500) NOT NULL,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_resena_comprador FOREIGN KEY (comprador_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  CONSTRAINT fk_resena_producto FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE CASCADE
);

-- mensajes
CREATE TABLE IF NOT EXISTS mensajes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remitente_id BIGINT NOT NULL,
  destinatario_id BIGINT NOT NULL,
  contenido VARCHAR(1000) NOT NULL,
  leido BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_mensaje_remitente FOREIGN KEY (remitente_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  CONSTRAINT fk_mensaje_destinatario FOREIGN KEY (destinatario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

-- notificaciones
CREATE TABLE IF NOT EXISTS notificaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destinatario_id BIGINT NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  contenido TEXT NOT NULL,
  leida BOOLEAN NOT NULL DEFAULT FALSE,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notificacion_destinatario FOREIGN KEY (destinatario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
