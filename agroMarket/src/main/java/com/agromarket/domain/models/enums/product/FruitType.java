package com.agromarket.domain.models.enums.product;

/**
 * Enumeración que representa los tipos de frutas disponibles en el catálogo de AgroMarket.
 * Se utiliza para clasificar productos por su tipo de fruta principal.
 * 
 * @author AgroMarket Team
 */
public enum FruitType {
    /**
     * Banano o plátano.
     */
    BANANA,
    
    /**
     * Mango.
     */
    MANGO,
    
    /**
     * Piña.
     */
    PINEAPPLE,
    
    /**
     * Maracuyá o granadilla.
     */
    PASSION_FRUIT,
    
    /**
     * Guanábana.
     */
    SOURSOP,
    
    /**
     * Naranja.
     */
    ORANGE,
    
    /**
     * Coco.
     */
    COCONUT,
    
    /**
     * Limón o lima.
     */
    LEMON,
    
    /**
     * Tipo de fruta no especificado o personalizado.
     */
    OTHER
}
